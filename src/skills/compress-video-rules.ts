/**
 * Rule engine for deterministic compression planning.
 *
 * This module implements the rule engine (Rule 6 of Phase 3) and matches the
 * upstream pixel-point/skills/compress-video rules structure. It provides
 * deterministic compression plans without relying on the AI model. AI is only
 * used for natural-language intent parsing and explanations.
 */

import type { VideoMetadata } from '../types/media';

export interface CompressionPlan {
  /**
   * Target codec for compression (h264, vp8, h265)
   * If not h264 and fallback is required, fallback to h264 with notice
   */
  targetCodec: 'h264' | 'vp8' | 'h265';

  /**
   * CRF value (Constant Rate Factor) for the target codec
   * Lower values = higher quality = larger files
   * Higher values = lower quality = smaller files
   */
  crf: number;

  /**
   * For h264, whether to use two-pass encoding for better quality/size ratio
   * (more computationally expensive)
   */
  twoPass?: boolean;

  /**
   * Target scale (width x height) for compression
   * If not provided, preserves original dimensions
   */
  targetScale?: { width: number; height: number };

  /**
   * Whether to preserve keyframes for cut-and-splice workflows
   */
  preserveKeyframes?: boolean;

  /**
   * Audio handling preferences
   */
  audioHandling?: 'copy' | 'encode' | 'strip';

  /**
   * Rule source for logging and debugging
   */
  ruleSource?: string;
}

/**
 * Evaluates a video metadata against the rule set to produce a compression plan.
 *
 * This implements Rule 6: deterministic rule engine fallback. The AI model is
 * only used for natural-language intent parsing and explanations (outside this
 * function). This function provides the deterministic fallback.
 *
 * @param metadata - Video metadata from ffprobe
 * @param intent - Natural language intent from user (optional, for rules that need it)
 * @returns CompressionPlan - Deterministic plan based on rules
 */
export function evaluateRules(
  metadata: VideoMetadata,
  intent?: string,
): CompressionPlan {
  // Rule 1: If video is larger than 100MB, compress more aggressively
  if (metadata.fileSize > 100 * 1024 * 1024) {
    return {
      targetCodec: 'h264',
      crf: 28,
      audioHandling: 'copy',
      preserveKeyframes: false,
      ruleSource: 'R1: Large file >100MB -> aggressive compression (CRF 28)',
    };
  }

  // Rule 2: If video is 4K (2160p), upscale to maintain quality when compressing
  if (metadata.width === 3840 && metadata.height === 2160) {
    return {
      targetCodec: 'h264',
      crf: 23,
      targetScale: { width: 3840, height: 2160 },
      twoPass: true,
      audioHandling: 'copy',
      preserveKeyframes: true,
      ruleSource: 'R2: 4K video -> maintain dimensions with two-pass CRF 23',
    };
  }

  // Rule 3: If video is longer than 30 seconds, use two-pass for better quality
  if (metadata.duration > 30) {
    return {
      targetCodec: 'h264',
      crf: 23,
      twoPass: true,
      audioHandling: 'copy',
      preserveKeyframes: false,
      ruleSource: 'R3: Long video (>30s) -> two-pass CRF 23',
    };
  }

  // Rule 4: If intent mentions "small", prioritize size over quality
  if (intent && intent.toLowerCase().includes('small')) {
    return {
      targetCodec: 'h264',
      crf: 32,
      audioHandling: 'strip',
      preserveKeyframes: false,
      ruleSource: 'R4: Intent mentions small -> aggressive CRF 32, strip audio',
    };
  }

  // Rule 5: If video is exactly 1280x720 (HD), use standard settings
  if (metadata.width === 1280 && metadata.height === 720) {
    return {
      targetCodec: 'h264',
      crf: 26,
      twoPass: false,
      audioHandling: 'copy',
      preserveKeyframes: true,
      ruleSource: 'R5: HD video (1280x720) -> standard CRF 26, preserve keyframes',
    };
  }

  // Rule 6: If video is 60fps, use higher CRF to maintain reasonable file size
  if (metadata.fps === 60) {
    return {
      targetCodec: 'h264',
      crf: 28,
      twoPass: true,
      audioHandling: 'copy',
      preserveKeyframes: false,
      ruleSource: 'R6: High frame rate (60fps) -> two-pass CRF 28',
    };
  }

  // Rule 7: Default fallback - use conservative settings
  return {
    targetCodec: 'h264',
    crf: 26,
    twoPass: false,
    audioHandling: 'copy',
    preserveKeyframes: true,
    ruleSource: 'R7: Default fallback -> CRF 26, preserve keyframes',
  };
}

/**
 * Generates a human-readable explanation for a given intent.
 *
 * Used outside the rule engine to provide natural language explanations of what
 * the compression plan means for the user.
 *
 * @param intent - Natural language intent from user
 * @param plan - Compression plan generated by evaluateRules
 * @returns Human-readable explanation
 */
export function generateExplanation(
  intent?: string,
  plan?: CompressionPlan,
): string {
  const intentText = intent ? `about "${intent}"` : '';
  const planDetails = plan
    ? `Target: ${plan.targetCodec} CRF ${plan.crf}${plan.twoPass ? ', two-pass' : ''}${plan.targetScale ? ` at ${plan.targetScale.width}x${plan.targetScale.height}` : ''}${plan.audioHandling ? `, ${plan.audioHandling} audio` : ''}${plan.preserveKeyframes ? ', preserve keyframes' : ''}`
    : '';

  return intent
    ? `For intent${intentText}, I recommend ${planDetails}. This follows our deterministic rule set to ensure consistent, predictable compression behavior without model variability.`
    : `Based on the deterministic rule set, the plan targets ${planDetails}. This ensures predictable compression without AI model influence, providing a reliable fallback for all users.`;
}
